import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ channel: 'chrome', headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:5175')
  await page.evaluate(() => {
    localStorage.setItem('kaoyan-agent-run-mode-v1', 'device')
    localStorage.setItem('kaoyan-device-agent-v1', JSON.stringify({ messages: [{ role: 'user', content: '保留旧记录' }, { role: 'assistant', content: '旧回复' }] }))
  })
  await page.goto('http://127.0.0.1:5175/mistake-review/index.html#home')
  const original = page.url()
  await page.locator('#settingsBtn svg').waitFor()
  await page.locator('#settingsBtn').tap()
  const frame = page.frameLocator('iframe[title="模型设置"]')
  await frame.getByLabel('配置名称').fill('验收模型')
  await frame.getByLabel('接口地址（Base URL）').fill('https://example.com/v1')
  await frame.getByLabel('对话模型', { exact: true }).fill('test-model')
  await frame.getByRole('button', { name: '保存并使用' }).click()
  await frame.getByText('已保存并设为当前模型。', { exact: true }).waitFor()
  assert.equal(page.url(), original)
  await frame.getByRole('button', { name: '完成，关闭设置' }).click()
  await page.locator('.agent-model-frame').waitFor({ state: 'detached' })
  await page.locator('#settingsBtn').tap()
  await frame.getByText('验收模型', { exact: true }).waitFor()
  await page.getByRole('button', { name: '关闭设置', exact: true }).click()
  assert.equal(page.url(), original)
  await page.locator('.agent-float-ball').tap()
  await page.getByRole('link', { name: '返回考研 Agent 首页', exact: true }).tap()
  await page.waitForURL('http://127.0.0.1:5175/')
  async function openChat() {
    await page.getByRole('button', { name: /学习 Agent 对话分析/ }).click()
    await page.getByRole('button', { name: '对话', exact: true }).click()
  }
  await openChat()
  await page.getByRole('button', { name: '之前的对话', exact: true }).waitFor()
  await page.getByText('保留旧记录', { exact: true }).waitFor()
  await page.getByRole('button', { name: '新建对话', exact: true }).click()
  await page.getByRole('button', { name: '重命名 新对话', exact: true }).click()
  await page.getByLabel('对话名称', { exact: true }).fill('积分复习')
  await page.getByRole('button', { name: '保存名称', exact: true }).click()
  await page.getByRole('button', { name: '新建对话', exact: true }).click()
  await page.getByRole('button', { name: '之前的对话', exact: true }).click()
  await page.getByText('保留旧记录', { exact: true }).waitFor()
  await page.reload()
  await openChat()
  await page.getByRole('button', { name: '积分复习', exact: true }).waitFor()
  await page.getByText('保留旧记录', { exact: true }).waitFor()
  await fs.mkdir('../.run/functional-review', { recursive: true })
  await page.screenshot({ path: '../.run/functional-review/conversations-mobile.png', fullPage: true })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'No mobile overflow')
  await page.getByRole('button', { name: '管理对话', exact: true }).click()
  await page.getByLabel('选择对话 新对话', { exact: true }).check()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '删除所选（1）', exact: true }).click()
  await page.getByRole('button', { name: '新对话', exact: true }).waitFor({ state: 'detached' })
  await page.getByRole('button', { name: '全选', exact: true }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '删除所选（2）', exact: true }).click()
  await page.getByText('还没有保存的对话', { exact: true }).waitFor()
  await page.reload()
  await openChat()
  await page.getByText('还没有保存的对话', { exact: true }).waitFor()
  assert.deepEqual(errors, [])
  console.log('PASS: in-place model settings/save/reopen, Agent home link, legacy migration, new/rename/switch/persist/single+batch delete, mobile overflow, no page errors')
} finally { await browser.close() }
