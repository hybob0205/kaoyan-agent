async function pressAction(name) {
  await page.locator('.agent-float-ball').tap()
  const node = page.getByRole('button', { name, exact: true })
  await node.waitFor({ state: 'visible' })
  await page.waitForTimeout(400)
  const before = await node.boundingBox()
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: before.x + before.width / 2, y: before.y + before.height / 2 }] })
  await page.waitForTimeout(200)
  const during = await node.boundingBox()
  assert.ok(Math.abs(before.x - during.x) < 2 && Math.abs(before.y - during.y) < 2, 'Pressed action must stay at its radial position')
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
}
