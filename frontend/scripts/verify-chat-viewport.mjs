import assert from 'node:assert/strict'
import fs from 'node:fs/promises'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ channel: 'chrome', headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:5175')
  await page.evaluate(() => localStorage.setItem('kaoyan-agent-run-mode-v1', 'device'))
  await page.reload()
  await page.getByRole('button', { name: /学习 Agent 对话分析/ }).click()
  await page.getByRole('button', { name: '对话', exact: true }).click()
  await page.getByRole('button', { name: '新建对话', exact: true }).click()
  await page.getByRole('button', { name: '打开历史对话' }).click()
  await page.getByRole('button', { name: '重命名 新对话' }).click()
  await page.getByLabel('对话名称', { exact: true }).fill('数学复习')
  await page.getByRole('button', { name: '保存名称' }).click()
  await page.getByRole('button', { name: '数学复习', exact: true }).click()
  await page.locator('.conversation-drawer').waitFor({ state: 'hidden' })
  await fs.mkdir('../.run/chat-viewport', { recursive: true })
  for (const [width, height] of [[390, 844], [390, 400], [320, 370], [844, 390], [768, 1024], [1440, 900]]) {
    await page.setViewportSize({ width, height })
    await page.locator('#device-agent-question').fill('输入时仍能看到问题和发送按钮')
    await page.waitForTimeout(150)
    const rect = await page.locator('#device-agent-question').boundingBox()
    assert.ok(rect.x >= 0 && rect.x + rect.width <= width + 1 && rect.y >= 0 && rect.y + rect.height <= height, `composer visible ${width}x${height}: ${JSON.stringify(rect)}`)
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'No document overflow')
    assert.equal(await page.locator('.agent-float-menu').isVisible(), false, 'Floating ball hides while typing')
    await page.screenshot({ path: `../.run/chat-viewport/${width}-${height}.png` })
  }
  await page.locator('#device-agent-question').blur()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.locator('.agent-float-ball').tap()
  await page.getByRole('link', { name: '去四科研习室', exact: true }).waitFor()
  await page.getByRole('link', { name: '去拾错', exact: true }).waitFor()
  await page.getByRole('link', { name: '返回考研 Agent 首页', exact: true }).tap()
  await page.getByRole('button', { name: /学习 Agent 对话分析/ }).waitFor()
  assert.equal(await page.locator('.agent-float-menu').count(), 0, 'Unmount cleans up floating ball')
  await page.getByRole('button', { name: /学习 Agent 对话分析/ }).click()
  await page.getByRole('button', { name: '对话', exact: true }).click()
  await page.getByRole('button', { name: '打开历史对话' }).click()
  await page.getByRole('button', { name: '管理对话', exact: true }).click()
  await page.getByLabel('选择对话 数学复习').check()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '删除所选（1）' }).click()
  await page.getByText('还没有保存的对话', { exact: true }).waitFor()
  assert.deepEqual(errors, [])
  console.log('PASS: drawer rename/select/delete, composer visible at 6 viewport sizes, no overflow, floating ball links/focus/unmount')
} finally { await browser.close() }
